export function Icon({ name, size = 14, className = "" }) {
  return (
    <svg width={size} height={size} viewBox="0 0 16 16" fill="currentColor" className={"shrink-0 " + className} aria-hidden="true">
      <path fillRule="evenodd" d={paths[name]} />
    </svg>
  );
}

export function Card({ title, actions, children, className = "", bodyClass = "card-body" }) {
  return (
    <div className={"card " + className}>
      {(title || actions) && (
        <div className="card-header">
          <span>{title}</span>
          <div className="ml-auto flex gap-2">{actions}</div>
        </div>
      )}
      <div className={bodyClass}>{children}</div>
    </div>
  );
}

export function Seg({ value, options, onChange, size = "sm" }) {
  return (
    <div className="inline-flex">
      {options.map(([v, label, title], i) => (
        <button key={v} type="button" title={title} onClick={() => onChange(v)}
          className={`btn btn-${size} ${value === v ? "btn-active" : "btn-default"} ${i ? "-ml-px rounded-l-none" : ""} ${i < options.length - 1 ? "rounded-r-none" : ""}`}>
          {label}
        </button>
      ))}
    </div>
  );
}

export function Tabs({ value, tabs, onChange }) {
  return (
    <div className="nav-tabs mb-4">
      {tabs.map(([v, label]) => (
        <button key={v} type="button" onClick={() => onChange(v)} className={"nav-tab " + (value === v ? "nav-tab-active" : "")}>
          {label}
        </button>
      ))}
    </div>
  );
}

export function Switch({ checked, onChange, label, hint }) {
  return (
    <label className="flex items-start gap-3 py-2.5 cursor-pointer border-b border-mc-border last:border-b-0 dark:border-mc-d-border">
      <span className="relative mt-0.5 shrink-0">
        <input type="checkbox" className="peer sr-only" checked={!!checked} onChange={(e) => onChange(e.target.checked)} />
        <span className="block w-9 h-5 rounded-full bg-[#cfcfcf] peer-checked:bg-mc-primary transition-colors dark:bg-[#5e5e5e]" />
        <span className="absolute left-0.5 top-0.5 w-4 h-4 rounded-full bg-white shadow transition-transform peer-checked:translate-x-4" />
      </span>
      <span>
        <span className="block font-semibold">{label}</span>
        {hint && <span className="block muted text-[12.5px]">{hint}</span>}
      </span>
    </label>
  );
}

export function Row({ label, children, top }) {
  return (
    <div className={"grid grid-cols-[130px_1fr] gap-3 mb-3 " + (top ? "items-start" : "items-center")}>
      <span className="text-[13px] font-semibold">{label}</span>
      <div>{children}</div>
    </div>
  );
}

export function Toast({ toast }) {
  if (!toast) return null;
  return (
    <div className={`fixed right-4 bottom-4 z-50 max-w-md px-4 py-2.5 rounded shadow-lg text-white text-[13px] ${toast.err ? "bg-mc-danger" : "bg-[#333]"}`}>
      {toast.msg}
    </div>
  );
}
